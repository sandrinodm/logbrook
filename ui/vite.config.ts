/**
 * Paths neither the formatter nor the linter touches: generated code, build output, dependencies
 * and the vendored component library.
 */
const ignoredPatterns = [
  '**/.claude/**',
  '**/dist/**',
  '**/node_modules/**',
  // Build output and caches of TanStack Start and Nitro.
  '**/.output/**',
  '**/.nitro/**',
  '**/.tanstack/**',
  // Reports and traces of the e2e runner.
  '**/.e2e/**',
  // Generated by the TanStack Router plugin.
  '**/routeTree.gen.ts',
  '**/*.tsbuildinfo',
  'pnpm-lock.yaml',
];

/**
 * Whether Vite is running the unit tests rather than serving or building the app.
 *
 * Vitest sets `VITEST` in the environment it loads the config in. The tests cover plain modules and
 * the proxy handlers, which need none of the app plugins; loading TanStack Start, Nitro and the
 * devtools there starts extra dev servers that keep the test process from exiting.
 */
const testing = process.env.VITEST !== undefined;

/**
 * How long one unit test may run before Vitest fails it, in milliseconds.
 */
const TEST_TIMEOUT_MILLIS = 5_000;

/**
 * Vite mode that builds with React's profiling bundle (`pnpm build:profile`). The browser then
 * reports component render times to the React DevTools Profiler and to the Performance panel's
 * React tracks, which a plain production build does not.
 */
const PROFILE_MODE = 'profile';

/**
 * Vite mode that writes `bundle-stats.json` with the size of every module in every client chunk
 * (`pnpm build:analyze`, read by `pnpm bundle-report`).
 */
const ANALYZE_MODE = 'analyze';

/**
 * Build plugin that records, for each chunk of the client build, the rendered (pre-gzip, minified)
 * size of the modules it contains. The numbers come from the bundler, so they are exact for the
 * chunk that ships; they are not gzip sizes.
 */
function bundleStats(): Plugin {
  return {
    name: 'logbrook-ui:bundle-stats',
    apply: 'build',
    generateBundle(_options, bundle) {
      if (this.environment.name !== 'client') {
        return;
      }

      const chunks = Object.values(bundle).flatMap((item) =>
        item.type === 'chunk'
          ? [
              {
                file: item.fileName,
                isEntry: item.isEntry,
                isDynamicEntry: item.isDynamicEntry,
                imports: item.imports,
                dynamicImports: item.dynamicImports,
                bytes: Buffer.byteLength(item.code),
                modules: Object.entries(item.modules).map(([id, info]) => ({
                  id,
                  bytes: info.renderedLength,
                })),
              },
            ]
          : [],
      );
      writeFileSync('bundle-stats.json', JSON.stringify(chunks));
    },
  };
}

/**
 * Vite+ config: formatting, type-aware lint, staged-file rules, the TanStack Start app on Nitro,
 * and the unit tests.
 *
 * In `profile` mode `react-dom/client` is replaced by `react-dom/profiling`, which has the same API
 * and keeps the instrumentation that production builds strip out, and minification is off so the
 * profiler shows component names.
 *
 * `devtools()` comes first because it must see the source before the other plugins transform it.
 * `tanstackStart` import protection keeps `src/server` and `*.server.*` modules, and the Node-only
 * packages they use, out of the client bundle. The React Compiler runs through
 * `@rolldown/plugin-babel` after the React plugin.
 */
export default defineConfig(({ mode }) => ({
  staged: {
    '*': 'vp check --fix',
    // jsdoc-lint checks a file named on the command line even when `jsdoc.json` excludes it, so
    // this glob leaves out tests, declarations, generated files and the vendored components itself.
    'src/!(components/ui)/**/!(*.test|*.spec|*.gen|*.d).{ts,tsx}': 'jsdoc-lint',
  },
  fmt: {
    arrowParens: 'always',
    bracketSameLine: true,
    bracketSpacing: true,
    jsdoc: { commentLineStrategy: 'multiline' },
    objectWrap: 'preserve',
    printWidth: 100,
    semi: true,
    singleQuote: true,
    sortImports: {
      groups: [
        'type-import',
        ['value-builtin', 'value-external'],
        'type-internal',
        'value-internal',
        ['type-parent', 'type-sibling', 'type-index'],
        ['value-parent', 'value-sibling', 'value-index'],
        'unknown',
      ],
    },
    sortPackageJson: true,
    sortTailwindcss: { stylesheet: './src/styles.css', functions: ['cn', 'cva'] },
    ignorePatterns: ignoredPatterns,
  },
  lint: {
    plugins: ['typescript', 'unicorn', 'oxc', 'jsdoc'],
    jsPlugins: [{ name: 'vite-plus', specifier: 'vite-plus/oxlint-plugin' }],
    rules: {
      curly: 'error',
      'jsdoc/check-tag-names': 'error',
      'jsdoc/check-access': 'error',
      'jsdoc/check-property-names': 'error',
      'jsdoc/require-property': 'off',
      'jsdoc/require-property-description': 'off',
      'jsdoc/require-property-name': 'off',
      'jsdoc/require-property-type': 'off',
      'jsdoc/require-yields': 'off',
      'typescript/no-deprecated': 'error',
      'vite-plus/prefer-vite-plus-imports': 'error',
    },
    // `vp check` is the type checker as well: there is no separate `tsc` step.
    options: { typeAware: true, typeCheck: true },
    ignorePatterns: ignoredPatterns,
    overrides: [
      {
        files: ['**/*.tsx'],
        plugins: ['react', 'react-perf', 'jsx-a11y'],
        rules: {
          'react/rules-of-hooks': 'error',
          'react/exhaustive-deps': 'warn',
        },
      },
      {
        files: ['**/*.{test,spec}.{ts,tsx}'],
        plugins: ['vitest'],
        rules: {
          // Vitest's expect(value, message) form is used for readable failures.
          'vitest/valid-expect': ['error', { maxArgs: 2 }],
          'vitest/require-mock-type-parameters': 'off',
        },
      },
    ],
  },
  // Profile builds keep component names; minified they read `t`, `n`, `r` in the profiler.
  build: mode === PROFILE_MODE ? { minify: false } : {},
  resolve: {
    tsconfigPaths: true,
    alias: mode === PROFILE_MODE ? { 'react-dom/client': 'react-dom/profiling' } : {},
  },
  plugins: testing
    ? []
    : [
        devtools(),
        ...(mode === ANALYZE_MODE ? [bundleStats()] : []),
        nitro({
          compressPublicAssets: { gzip: true, brotli: true },
          // Fails at boot, not on the first request, when the environment is wrong.
          plugins: ['./src/server/startup.server.ts'],
          // Nitro imports polyfills before its Node server reads `HOST`, which is the only place
          // to give the server a loopback default: the runtime has no host option.
          unenv: { polyfill: ['./src/server/default-host.server.ts'] },
        }),
        tailwindcss(),
        tanstackStart({
          importProtection: {
            client: { files: ['**/*.server.*', '**/src/server/**'] },
          },
        }),
        viteReact(),
        babel({ presets: [reactCompilerPreset()] }),
      ],
  test: {
    include: ['src/**/*.test.ts', 'src/**/*.test.tsx'],
    testTimeout: TEST_TIMEOUT_MILLIS,
    hookTimeout: TEST_TIMEOUT_MILLIS,
  },
  run: { cache: { scripts: false, tasks: true } },
}));
